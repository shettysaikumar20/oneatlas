function buildMockModel(
  id: string,
  slug: string,
  name: string,
  desc: string,
  labSlug: string,
  type: string,
  ctx: number,
  inPrice: number,
  outPrice: number,
  release: string,
  license: string,
  params: string,
  isFeatured: boolean,
  caps: string[],
  scores: Record<string, number>,
  provs: { slug: string; inPrice: number; outPrice: number; lat: number; tps: number; up: number; def?: boolean }[]
): ModelListItem {
  const lab = MOCK_LABS.find((l) => l.slug === labSlug) || MOCK_LABS[0];
  return {
    id,
    slug,
    name,
    description: desc,
    labId: lab.id,
    modelType: type,
    contextWindow: ctx,
    maxOutputTokens: 8192,
    inputPricePerM: inPrice,
    outputPricePerM: outPrice,
    releaseDate: release,
    license,
    parameters: params,
    isFeatured,
    lab,
    capabilities: caps.map((cSlug) => {
      const c = MOCK_CAPABILITIES.find((cap) => cap.slug === cSlug) || MOCK_CAPABILITIES[0];
      return {
        id: `mc-${id}-${c.slug}`,
        modelId: id,
        capabilityId: c.id,
        capability: c,
      };
    }),
    modalities:
      type === "multimodal"
        ? [
            { id: `m1-${id}`, modelId: id, modalityType: "text", direction: "input" },
            { id: `m2-${id}`, modelId: id, modalityType: "text", direction: "output" },
            { id: `m3-${id}`, modelId: id, modalityType: "image", direction: "input" },
          ]
        : [
            { id: `m1-${id}`, modelId: id, modalityType: "text", direction: "input" },
            { id: `m2-${id}`, modelId: id, modalityType: "text", direction: "output" },
          ],
    providers: provs.map((p) => {
      const provider = MOCK_PROVIDERS.find((pr) => pr.slug === p.slug) || MOCK_PROVIDERS[0];
      return {
        id: `mp-${id}-${provider.slug}`,
        modelId: id,
        providerId: provider.id,
        inputPricePerM: p.inPrice,
        outputPricePerM: p.outPrice,
        latencyMs: p.lat,
        throughput: p.tps,
        uptimePercent: p.up,
        isDefault: Boolean(p.def),
        contextWindow: ctx,
        provider,
      };
    }),
    benchmarkScores: Object.entries(scores).map(([bSlug, score]) => {
      const benchmark = MOCK_BENCHMARKS.find((b) => b.slug === bSlug) || MOCK_BENCHMARKS[0];
      return {
        id: `bs-${id}-${benchmark.slug}`,
        modelId: id,
        benchmarkId: benchmark.id,
        score,
        sourceUrl: "https://lmsys.org",
        verified: true,
        benchmark,
      };
    }),
  };
}

